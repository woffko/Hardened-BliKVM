#!/usr/bin/env python3
"""Render the native-profile unit replacements from the base units.

systemd drop-ins cannot remove dependencies, so the native profile replaces
the managed units completely. Each rendered unit is the base unit with a
closed list of edits; every edit must apply exactly once, so base-unit drift
fails the render instead of silently producing a stale profile.

Usage: render_native_profile.py [--check]
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "packaging" / "systemd"
NATIVE = BASE / "native"
EXEC = "/var/lib/hardened-blikvm-exec/current"
SLOTS = "/var/lib/hardened-blikvm-slots/current"
LIBEXEC = "/usr/libexec/hardened-blikvm"
RECOVER = "hardened-blikvm-update-recover.service"
CONFIRM = "hardened-blikvm-update-confirm.socket"


@dataclass(frozen=True)
class Edit:
    old: str
    new: str


def dependency_edits(line_prefix: str, line: str, removed: tuple[str, ...]) -> Edit:
    tokens = line.removeprefix(line_prefix).split()
    kept = [token for token in tokens if token not in removed]
    if len(kept) + len(removed) != len(tokens):
        raise SystemExit(f"dependency drift in {line!r}")
    return Edit(line + "\n", f"{line_prefix}{' '.join(kept)}\n" if kept else "")


def unit_line(text: str, prefix: str) -> str:
    lines = [line for line in text.splitlines() if line.startswith(prefix)]
    if len(lines) != 1:
        raise SystemExit(f"expected one {prefix!r} line, found {len(lines)}")
    return lines[0]


def without_install(text: str) -> str:
    marker = "\n[Install]\n"
    if text.count(marker) != 1:
        raise SystemExit("expected exactly one [Install] section")
    head, tail = text.split(marker)
    if "\n[" in tail:
        raise SystemExit("[Install] must be the last section")
    return head.rstrip("\n") + "\n"


def apply(name: str, text: str, edits: list[Edit], keep_install: bool = False) -> str:
    for edit in edits:
        if text.count(edit.old) != 1:
            raise SystemExit(f"{name}: edit {edit.old!r} matched {text.count(edit.old)} times")
        text = text.replace(edit.old, edit.new)
    if not keep_install:
        text = without_install(text)
    header = (
        f"# Generated by tools/render_native_profile.py from packaging/systemd/{name}.\n"
        "# Native profile: started only by the root execution helper. Do not edit.\n"
    )
    return header + text


def render() -> dict[str, str]:
    rendered: dict[str, str] = {}

    name = "hardened-blikvm-board-owner.service"
    text = (BASE / name).read_text()
    rendered[name] = apply(
        name,
        text,
        [Edit(f"ExecStart={LIBEXEC}/bli-kvm-control-broker\n", f"ExecStart={EXEC}/libexec/bli-kvm-control-broker\n")],
    )

    name = "hardened-blikvm-board-video-proxy.service"
    text = (BASE / name).read_text()
    rendered[name] = apply(
        name,
        text,
        [Edit(f"ExecStart={LIBEXEC}/bli-kvm-video-proxy\n", f"ExecStart={EXEC}/libexec/bli-kvm-video-proxy\n")],
    )

    name = "hardened-blikvm-boardd.service"
    text = (BASE / name).read_text()
    rendered[name] = apply(
        name,
        text,
        [Edit(f"ExecStart={LIBEXEC}/bli-kvm-boardd ", f"ExecStart={EXEC}/libexec/bli-kvm-boardd ")],
    )

    name = "hardened-blikvm-server-current.service"
    text = (BASE / name).read_text()
    edits = [
        dependency_edits("Requires=", unit_line(text, "Requires="), (RECOVER,)),
        dependency_edits("After=", unit_line(text, "After="), (RECOVER,)),
    ]
    edits.append(native_admission(text))
    text = apply(name, text, edits)
    rendered[name] = replace_slots(name, text, 4)

    name = "hardened-blikvm-server-candidate.service"
    text = (BASE / name).read_text()
    post = unit_line(text, "ExecStartPost=")
    edits = [
        dependency_edits("Requires=", unit_line(text, "Requires="), (CONFIRM, RECOVER)),
        dependency_edits("After=", unit_line(text, "After="), (CONFIRM, RECOVER)),
        Edit("ConditionPathExists=/run/hardened-blikvm-update/health-token\n", ""),
        Edit(
            "LoadCredential=application-health-token:/run/hardened-blikvm-update/health-token\n",
            "",
        ),
        # Native confirmation belongs to the coordinator after full composition health.
        Edit(post + "\n", ""),
        native_admission(text),
    ]
    text = apply(name, text, edits, keep_install="\n[Install]\n" not in text)
    rendered[name] = replace_slots(name, text, 4)

    name = "hardened-blikvm-update-activation@.service"
    text = (BASE / name).read_text()
    rendered[name] = apply(
        name,
        text,
        [
            # Native success is already a confirmed composition; never
            # dispatch the legacy apply services after it.
            Edit(unit_line(text, "OnSuccess=") + "\n", ""),
            Edit("TimeoutStartSec=15s\n", "TimeoutStartSec=100s\n"),
            Edit(
                " activation-socket --peer-user hardened-blikvm-server\n",
                " activation-socket --peer-user hardened-blikvm-server --native-profile\n",
            ),
        ],
        keep_install=True,
    )
    return rendered


def native_admission(text: str) -> Edit:
    anchor = unit_line(text, "Environment=BLI_KVM_BIND=")
    return Edit(anchor + "\n", anchor + "\nEnvironment=BLI_KVM_UPDATE_NATIVE_ADMISSION=1\n")


def replace_slots(name: str, text: str, expected: int) -> str:
    count = text.count(SLOTS)
    if count != expected:
        raise SystemExit(f"{name}: expected {expected} slot paths, found {count}")
    return text.replace(SLOTS, EXEC)


def main() -> int:
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        print(__doc__, file=sys.stderr)
        return 2
    rendered = render()
    stale = []
    for name, text in sorted(rendered.items()):
        path = NATIVE / name
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            NATIVE.mkdir(exist_ok=True)
            path.write_text(text)
    extra = sorted(
        path.name for path in NATIVE.glob("*") if path.name not in rendered
    ) if NATIVE.exists() else []
    if check and (stale or extra):
        print(f"native profile is stale: {stale + extra}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
