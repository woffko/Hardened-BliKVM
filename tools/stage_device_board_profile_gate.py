#!/usr/bin/env python3
"""Stage the board-owner profile on the test H616, reversibly.

This is the physical-gate runner: it stops KVMD, starts the Rust board owner
from the verified bundle under a single reserved `/run` directory, verifies the
owner socket and the `hardened` gadget, and can tear everything down again,
removing only the `hardened` gadget and restarting KVMD. It never touches the
`kvmd` gadget, the retained slots or the permanent write policy.

Execution requires `--confirm-handoff`; without it the tool validates inputs and
prints the plan. The remote shell is generated by pure functions and host-tested.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

if not __package__:
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from tools.capture_pikvm_baseline import write_json_0600_atomic
from tools import stage_device_prototype as prototype
from tools import plan_board_profile_handoff as planner

RUNTIME_ROOT = "/var/lib/hardened-blikvm-gadget/gate"
MARKER = f"{RUNTIME_ROOT}/.hardened-blikvm-gate"
APPLY_FACTS = {
    "kvmd_was_active",
    "owner_started",
    "socket_present",
    "gadget_present",
    "udc_bound",
    "gadget_name",
    "kvmd_stopped",
}
TEARDOWN_FACTS = {
    "owner_stopped",
    "hardened_gadget_removed",
    "runtime_removed",
    "kvmd_restarted",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--endpoint", required=True)
    _ = parser.add_argument("--username", required=True)
    _ = parser.add_argument("--known-hosts", required=True)
    _ = parser.add_argument("--bundle", required=True)
    _ = parser.add_argument("--output", required=True)
    _ = parser.add_argument("--udc", required=True)
    _ = parser.add_argument("--power-short-ms", required=True, type=int)
    _ = parser.add_argument("--power-long-ms", required=True, type=int)
    _ = parser.add_argument("--reset-ms", required=True, type=int)
    _ = parser.add_argument("--confirm-handoff", action="store_true")
    _ = parser.add_argument("--teardown", action="store_true")
    return parser.parse_args()


def _env_lines(environment: dict[str, str]) -> str:
    return "\n".join(f"{key}={value}" for key, value in sorted(environment.items()))


def _env_args(environment: dict[str, str]) -> str:
    return " ".join(f"{key}={value}" for key, value in sorted(environment.items()))


def build_apply_script(plan: dict[str, Any], bundle_sha256: str) -> str:
    owner_env = plan["ownerEnvironment"]
    atx_env = plan["atxEnvironmentFile"]
    return f"""set -eu
root={RUNTIME_ROOT}
marker={MARKER}
mkdir -p "$root"
: > "$marker"
if [ ! -f "$root/bundle.tar.gz" ]; then echo "missing bundle.tar.gz" >&2; exit 1; fi
expected={bundle_sha256}
actual=$(sha256sum "$root/bundle.tar.gz" | cut -d ' ' -f 1)
if [ "$actual" != "$expected" ]; then echo "bundle sha mismatch" >&2; exit 1; fi
tar -xzf "$root/bundle.tar.gz" -C "$root"
broker="$root/{planner.BUNDLE_ROOT}/libexec/bli-kvm-control-broker"
mkdir -p "$root/state" "$root/atx"
cat > "$root/atx.env" <<'ATXEOF'
{_env_lines(atx_env)}
ATXEOF
if systemctl is-active kvmd.service >/dev/null 2>&1; then printf 'kvmd_was_active=yes\\n'; else printf 'kvmd_was_active=no\\n'; fi
systemctl stop kvmd.service >/dev/null 2>&1 || true
if systemctl is-active kvmd.service >/dev/null 2>&1; then printf 'kvmd_stopped=no\\n'; else printf 'kvmd_stopped=yes\\n'; fi
env -i PATH=/usr/sbin:/usr/bin:/sbin:/bin HOME=/root {_env_args(owner_env)} setsid "$broker" >"$root/owner.log" 2>&1 &
owner_pid=$!
printf '%s' "$owner_pid" > "$root/owner.pid"
socket=$(printf '%s' "{owner_env['BLI_KVM_CONTROL_SOCKET']}")
i=0
while [ "$i" -lt 40 ]; do
  if [ -S "$socket" ]; then break; fi
  i=$((i + 1)); sleep 0.5
done
if [ -S "$socket" ]; then printf 'socket_present=yes\\n'; else printf 'socket_present=no\\n'; fi
if kill -0 "$owner_pid" 2>/dev/null; then printf 'owner_started=yes\\n'; else printf 'owner_started=no\\n'; fi
gdir=/sys/kernel/config/usb_gadget
if [ -d "$gdir/hardened" ]; then printf 'gadget_present=yes\\n'; printf 'gadget_name=hardened\\n'; else printf 'gadget_present=no\\n'; printf 'gadget_name=none\\n'; fi
if [ -n "$(cat "$gdir/hardened/UDC" 2>/dev/null | tr -d '\\n')" ]; then printf 'udc_bound=yes\\n'; else printf 'udc_bound=no\\n'; fi
"""


def build_teardown_script() -> str:
    return f"""set -eu
root={RUNTIME_ROOT}
marker={MARKER}
if [ -f "$root/owner.pid" ]; then
  pid=$(cat "$root/owner.pid")
  kill "$pid" >/dev/null 2>&1 || true
  i=0
  while [ "$i" -lt 20 ] && kill -0 "$pid" 2>/dev/null; do i=$((i + 1)); sleep 0.5; done
  kill -9 "$pid" >/dev/null 2>&1 || true
  printf 'owner_stopped=yes\\n'
else
  printf 'owner_stopped=yes\\n'
fi
gdir=/sys/kernel/config/usb_gadget
if [ -d "$gdir/hardened" ] && [ -f "$marker" ]; then
  printf '' > "$gdir/hardened/UDC" || true
  for link in "$gdir"/hardened/configs/*/*; do
    [ -L "$link" ] || continue
    rm -f -- "$link"
  done
  for fn in "$gdir"/hardened/functions/*; do
    [ -d "$fn" ] || continue
    rmdir "$fn" 2>/dev/null || true
  done
  for directory in "$gdir"/hardened/configs/*/strings/* "$gdir"/hardened/configs/* "$gdir"/hardened/strings/* "$gdir"/hardened; do
    [ -d "$directory" ] || continue
    rmdir "$directory" 2>/dev/null || true
  done
fi
if [ ! -d "$gdir/hardened" ]; then printf 'hardened_gadget_removed=yes\\n'; else printf 'hardened_gadget_removed=no\\n'; fi
rm -rf -- "$root"
if [ ! -e "$root" ]; then printf 'runtime_removed=yes\\n'; else printf 'runtime_removed=no\\n'; fi
systemctl start kvmd.service >/dev/null 2>&1 || true
if systemctl is-active kvmd.service >/dev/null 2>&1; then printf 'kvmd_restarted=yes\\n'; else printf 'kvmd_restarted=no\\n'; fi
"""


def validate_apply(facts: dict[str, str]) -> None:
    for key, expected in (("socket_present", "yes"), ("owner_started", "yes"), ("udc_bound", "yes")):
        if facts[key] != expected:
            raise ValueError(f"apply gate failed: {key}={facts[key]}")
    if facts["gadget_name"] != "hardened":
        raise ValueError("apply gate did not own the hardened gadget")


def validate_teardown(facts: dict[str, str]) -> None:
    for key in ("owner_stopped", "hardened_gadget_removed", "runtime_removed", "kvmd_restarted"):
        if facts[key] != "yes":
            raise ValueError(f"teardown gate failed: {key}={facts[key]}")


def parse_args_into_plan(options: argparse.Namespace, bundle_path: Path) -> dict[str, Any]:
    import argparse as _argparse

    plan_options = _argparse.Namespace(
        bundle=str(bundle_path),
        output="",
        udc=options.udc,
        power_short_ms=options.power_short_ms,
        power_long_ms=options.power_long_ms,
        reset_ms=options.reset_ms,
        configfs_root=planner.CONFIGFS_ROOT,
        images_dir=f"{planner.GADGET_STATE}/images",
        catalog=f"{planner.GADGET_ETC}/catalog.json",
        serial_file=f"{planner.GADGET_ETC}/serial",
        atx_journal=f"{planner.GADGET_STATE}/atx-journal.json",
        hid_ledger=f"{planner.GADGET_STATE}/hid-ledger.json",
        control_socket=f"{planner.GADGET_RUN}/control.sock",
        atx_chip="/dev/gpiochip0",
        hidg_dir=planner.HIDG_DIR,
        reconciliations="",
    )
    from tools import verify_board_profile_bundle as bundle_verifier

    verified = bundle_verifier.verify_bundle(bundle_path, "")
    plan = planner.build_plan(plan_options, str(verified["sha256"]))
    return plan


def execute(args: argparse.Namespace) -> int:
    output = prototype.validate_output_path(args.output)
    bundle = Path(args.bundle).resolve(strict=True)
    plan = parse_args_into_plan(args, bundle)
    receipt: dict[str, Any] = {
        "schemaVersion": 1,
        "gate": "hardened-blikvm-board-profile-handoff",
        "bundleSha256": plan["bundle"]["sha256"],
        "plan": plan,
        "confirmed": bool(args.confirm_handoff),
        "ownerEnvironment": plan["ownerEnvironment"],
    }
    if not args.confirm_handoff:
        write_json_0600_atomic(output, receipt)
        print(f"board_gate_plan_only={output} (pass --confirm-handoff to execute)")
        return 0

    host, ssh_port = prototype.parse_endpoint(args.endpoint)
    username = prototype.validate_username(args.username)
    known_hosts = prototype.validate_private_file(args.known_hosts)
    target = prototype.RemoteTarget(host, ssh_port, username, known_hosts)
    secret = prototype.read_secret_stdin()

    if args.teardown:
        result = prototype.run_ssh(target, secret, build_teardown_script(), timeout=60)
        result.check_returncode()
        facts = prototype.parse_facts(result.stdout, set(TEARDOWN_FACTS))
        validate_teardown(facts)
        receipt["teardownFacts"] = facts
    else:
        try:
            apply = prototype.run_ssh(
                target,
                secret,
                build_apply_script(plan, str(plan["bundle"]["sha256"])),
                timeout=120,
            )
            apply.check_returncode()
            facts = prototype.parse_facts(apply.stdout, set(APPLY_FACTS))
            validate_apply(facts)
        except Exception:
            try:
                prototype.run_ssh(target, secret, build_teardown_script(), timeout=60)
            except Exception:
                pass
            raise
        receipt["applyFacts"] = facts

    receipt["mutationsPerformed"] = True
    serialized = json.dumps(receipt, sort_keys=True)
    digest = hashlib.sha256(serialized.encode()).hexdigest()
    write_json_0600_atomic(output, receipt)
    print(f"board_gate={output} receiptSha256={digest}")
    return 0


def main() -> int:
    try:
        return execute(parse_args())
    except (OSError, UnicodeError, ValueError, subprocess.SubprocessError) as error:
        _ = error
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
