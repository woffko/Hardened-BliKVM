#!/usr/bin/env python3
"""Stage the board-owner profile on the test H616, reversibly.

This is the physical-gate runner: it stops KVMD, starts the Rust board owner
from the verified bundle under a single reserved `/run` directory, verifies the
owner socket and the `hardened` gadget, and can tear everything down again,
removing only the `hardened` gadget and restarting KVMD. It never touches the
`kvmd` gadget, the retained slots or the permanent write policy.

With `--accept-media-hid` the apply phase also waits for the composite gadget the
board owner creates on the first media attach, records its functions, the
attached catalog image and the hidg character devices, and writes one neutral
(release-all) keyboard report to prove the report path. The USB/HID effect on
the target is confirmed by the operator; the gate records only what the board
shows.

Execution requires `--confirm-handoff`; without it the tool validates inputs and
prints the plan. The remote shell is generated by pure functions and host-tested.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

if not __package__:
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from tools.capture_pikvm_baseline import write_json_0600_atomic
from tools import stage_device_prototype as prototype
from tools import plan_board_profile_handoff as planner

RUNTIME_ROOT = "/var/lib/hardened-blikvm-gadget/gate"
MARKER = f"{RUNTIME_ROOT}/.hardened-blikvm-gate"
APPLY_FACTS = {
    "kvmd_was_active",
    "owner_started",
    "socket_present",
    "gadget_present",
    "udc_bound",
    "gadget_name",
    "kvmd_stopped",
    "kvmd_udc_unbound",
    "kvmd_gadget",
    "udc_bound",
}
TEARDOWN_FACTS = {
    "owner_stopped",
    "hardened_gadget_removed",
    "runtime_removed",
    "kvmd_restarted",
    "kvmd_udc_bound",
}
ATX_BENCH_ACTIONS = ("power_short", "power_long", "reset")
ATX_BENCH_FACTS = {"run_rc"} | {
    f"{action}_{suffix}"
    for action in ATX_BENCH_ACTIONS
    for suffix in ("elapsed_ms", "expected_ms", "within_tolerance", "")
}
ACCEPTANCE_FACTS = {
    "gadget_present",
    "gadget_name",
    "udc_bound",
    "functions",
    "msd_file",
    "hidg_devices",
    "hid_write",
}
EXPECTED_GADGET_FUNCTIONS = {"hid.usb0", "hid.usb1", "hid.usb2", "mass_storage.usb0"}
DEFAULT_ACCEPT_TIMEOUT_SECONDS = 180
MAX_ACCEPT_TIMEOUT_SECONDS = 600
MSD_BASENAME = re.compile(r"^[A-Za-z0-9._-]{1,64}$")
HIDG_DEVICE = re.compile(r"^/dev/hidg[0-9]{1,2}$")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--endpoint", required=True)
    _ = parser.add_argument("--username", required=True)
    _ = parser.add_argument("--known-hosts", required=True)
    _ = parser.add_argument("--bundle", required=True)
    _ = parser.add_argument("--output", required=True)
    _ = parser.add_argument("--udc", required=True)
    _ = parser.add_argument(
        "--power-short-ms",
        default=planner.VENDOR_ATX_POWER_SHORT_MS,
        type=int,
    )
    _ = parser.add_argument(
        "--power-long-ms",
        default=planner.VENDOR_ATX_POWER_LONG_MS,
        type=int,
    )
    _ = parser.add_argument("--reset-ms", default=planner.VENDOR_ATX_RESET_MS, type=int)
    _ = parser.add_argument("--confirm-handoff", action="store_true")
    _ = parser.add_argument("--teardown", action="store_true")
    _ = parser.add_argument("--accept-media-hid", action="store_true")
    _ = parser.add_argument(
        "--accept-timeout-seconds",
        type=int,
        default=DEFAULT_ACCEPT_TIMEOUT_SECONDS,
    )
    _ = parser.add_argument("--accept-image", default="kubuntu.img")
    _ = parser.add_argument("--takeover-udc", action="store_true")
    _ = parser.add_argument("--accept-atx-bench", action="store_true")
    _ = parser.add_argument("--confirm-physical-disconnect", action="store_true")
    _ = parser.add_argument("--atx-chip", default="/dev/gpiochip0")
    return parser.parse_args()


def _env_lines(environment: dict[str, str]) -> str:
    return "\n".join(f"{key}={value}" for key, value in sorted(environment.items()))


def _env_args(environment: dict[str, str]) -> str:
    return " ".join(f"{key}={value}" for key, value in sorted(environment.items()))


def build_apply_script(
    plan: dict[str, Any], bundle_sha256: str, takeover_udc: bool = False
) -> str:
    owner_env = plan["ownerEnvironment"]
    atx_env = plan["atxEnvironmentFile"]
    if takeover_udc:
        # The board has one UDC and KVMD holds it; the owner cannot bind its own
        # gadget until KVMD's gadget is unbound. Teardown proves it is bound
        # again after KVMD restarts.
        # One UDC, held by the KVMD gadget. The vendor OTG helper rebinds it, so
        # stopping kvmd.service alone is not enough: the OTG and main units must
        # stop first, then the UDC is released (or unbound explicitly).
        # One UDC, held by the KVMD gadget. The vendor OTG unit removes its
        # gadget when it stops, so the UDC is released either way; verify from
        # the UDC state instead of assuming.
        udc_name = str(owner_env["BLI_KVM_GADGET_UDC"])
        # One UDC. The vendor OTG unit removes its gadget when it stops, so the
        # controller is free once no gadget directory binds it; the kernel's
        # per-UDC state file is stale on this board and is not used.
        udc_block = (
            "gdir0=/sys/kernel/config/usb_gadget\n"
            "systemctl stop kvmd-otg.service kvmd-main.service >/dev/null 2>&1 || true\n"
            "i=0\n"
            "while [ \"$i\" -lt 20 ]; do\n"
            "  bound=\"\"\n"
            "  for gadget in \"$gdir0\"/*; do\n"
            "    [ -d \"$gadget\" ] || continue\n"
            "    if [ -n \"$(cat \"$gadget/UDC\" 2>/dev/null | tr -d '\\n')\" ]; then bound=$(basename \"$gadget\"); break; fi\n"
            "  done\n"
            "  [ -z \"$bound\" ] && break\n"
            "  i=$((i + 1)); sleep 0.5\n"
            "done\n"
            "if [ -d \"$gdir0/kvmd\" ] && [ -n \"$(cat \"$gdir0/kvmd/UDC\" 2>/dev/null | tr -d '\\n')\" ]; then\n"
            "  printf '' > \"$gdir0/kvmd/UDC\" || true\n"
            "  bound=\"\"\n"
            "  for gadget in \"$gdir0\"/*; do\n"
            "    [ -d \"$gadget\" ] || continue\n"
            "    if [ -n \"$(cat \"$gadget/UDC\" 2>/dev/null | tr -d '\\n')\" ]; then bound=$(basename \"$gadget\"); break; fi\n"
            "  done\n"
            "fi\n"
            "if [ -d \"$gdir0/kvmd\" ]; then printf 'kvmd_gadget=present\\n'; else printf 'kvmd_gadget=absent\\n'; fi\n"
            "printf 'udc_bound=%s\\n' \"${bound:-none}\"\n"
            "if [ -z \"$bound\" ]; then printf 'kvmd_udc_unbound=yes\\n'; else printf 'kvmd_udc_unbound=no\\n'; fi\n"
        )
    else:
        udc_block = (
            "printf 'kvmd_gadget=absent\\n'\n"
            "printf 'udc_bound=kvmd\\n'\n"
            "printf 'kvmd_udc_unbound=absent\\n'\n"
        )
    return f"""set -eu
root={RUNTIME_ROOT}
marker={MARKER}
mkdir -p "$root"
: > "$marker"
if [ ! -f "$root/bundle.tar.gz" ]; then echo "missing bundle.tar.gz" >&2; exit 1; fi
expected={bundle_sha256}
actual=$(sha256sum "$root/bundle.tar.gz" | cut -d ' ' -f 1)
if [ "$actual" != "$expected" ]; then echo "bundle sha mismatch" >&2; exit 1; fi
tar -xzf "$root/bundle.tar.gz" -C "$root"
broker="$root/{planner.BUNDLE_ROOT}/libexec/bli-kvm-control-broker"
mkdir -p "$root/state" "$root/atx"
cat > "$root/atx.env" <<'ATXEOF'
{_env_lines(atx_env)}
ATXEOF
if systemctl is-active kvmd.service >/dev/null 2>&1; then printf 'kvmd_was_active=yes\\n'; else printf 'kvmd_was_active=no\\n'; fi
systemctl stop kvmd.service >/dev/null 2>&1 || true
if systemctl is-active kvmd.service >/dev/null 2>&1; then printf 'kvmd_stopped=no\\n'; else printf 'kvmd_stopped=yes\\n'; fi
{udc_block}env -i PATH=/usr/sbin:/usr/bin:/sbin:/bin HOME=/root {_env_args(owner_env)} setsid "$broker" >"$root/owner.log" 2>&1 &
owner_pid=$!
printf '%s' "$owner_pid" > "$root/owner.pid"
socket=$(printf '%s' "{owner_env['BLI_KVM_CONTROL_SOCKET']}")
rm -f -- "$socket"
i=0
while [ "$i" -lt 40 ]; do
  if [ -S "$socket" ]; then break; fi
  i=$((i + 1)); sleep 0.5
done
if [ -S "$socket" ]; then printf 'socket_present=yes\\n'; else printf 'socket_present=no\\n'; fi
if kill -0 "$owner_pid" 2>/dev/null; then printf 'owner_started=yes\\n'; else printf 'owner_started=no\\n'; fi
gdir=/sys/kernel/config/usb_gadget
if [ -d "$gdir/hardened" ]; then printf 'gadget_present=yes\\n'; printf 'gadget_name=hardened\\n'; else printf 'gadget_present=no\\n'; printf 'gadget_name=none\\n'; fi
if [ -n "$(cat "$gdir/hardened/UDC" 2>/dev/null | tr -d '\\n')" ]; then printf 'udc_bound=yes\\n'; else printf 'udc_bound=no\\n'; fi
"""


def build_atx_bench_script(chip: str, timing: tuple[int, int, int]) -> str:
    """Run the native GPIO bench from the extracted bundle, mutation-gated."""
    if not re.fullmatch(r"/dev/gpiochip[0-9]{1,3}", chip):
        raise ValueError("ATX bench chip is invalid")
    short, long_hold, reset = timing
    for value in timing:
        if not 1 <= value <= 10_000:
            raise ValueError("ATX bench timing is out of range")
    binary = f"{RUNTIME_ROOT}/{planner.BUNDLE_ROOT}/libexec/bli-kvm-atx-gpio-bench-gate"
    return f"""set -eu
if [ ! -x "{binary}" ]; then echo "atx bench binary is missing" >&2; exit 1; fi
env -i PATH=/usr/sbin:/usr/bin:/sbin:/bin \
  BLI_KVM_ATX_BENCH_CONFIRM=1 \
  BLI_KVM_ATX_CHIP={chip} \
  BLI_KVM_ATX_POWER_SHORT_MS={short} \
  BLI_KVM_ATX_POWER_LONG_MS={long_hold} \
  BLI_KVM_ATX_RESET_MS={reset} \
  "{binary}"
"""


def validate_atx_bench(facts: dict[str, str]) -> None:
    if facts["run_rc"] != "0":
        raise ValueError("ATX bench reported a failure")
    for action in ATX_BENCH_ACTIONS:
        if facts[f"{action}"] != "ok" or facts[f"{action}_within_tolerance"] != "yes":
            raise ValueError(
                f"ATX bench {action} drifted: {facts[f'{action}_elapsed_ms']} ms "
                f"against {facts[f'{action}_expected_ms']} ms"
            )


def build_acceptance_script(timeout_seconds: int, expected_image: str) -> str:
    if not 1 <= timeout_seconds <= MAX_ACCEPT_TIMEOUT_SECONDS:
        raise ValueError("acceptance timeout is out of range")
    if not MSD_BASENAME.fullmatch(expected_image):
        raise ValueError("expected image name is invalid")
    return f"""set -eu
gdir=/sys/kernel/config/usb_gadget
expected={expected_image}
waited=0
while [ "$waited" -lt {timeout_seconds} ]; do
  if [ -d "$gdir/hardened" ] && [ -n "$(cat "$gdir/hardened/UDC" 2>/dev/null | tr -d '\n')" ]; then break; fi
  waited=$((waited + 2)); sleep 2
done
if [ -d "$gdir/hardened" ]; then printf 'gadget_present=yes\n'; printf 'gadget_name=hardened\n'; else printf 'gadget_present=no\n'; printf 'gadget_name=none\n'; fi
if [ -n "$(cat "$gdir/hardened/UDC" 2>/dev/null | tr -d '\n')" ]; then printf 'udc_bound=yes\n'; else printf 'udc_bound=no\n'; fi
functions=""
for path in "$gdir"/hardened/functions/*; do
  [ -d "$path" ] || continue
  if [ -z "$functions" ]; then functions=$(basename "$path"); else functions="$functions,$(basename "$path")"; fi
done
printf 'functions=%s\n' "$functions"
file=$(cat "$gdir/hardened/functions/mass_storage.usb0/lun.0/file" 2>/dev/null | tr -d '\n' || true)
if [ -n "$file" ]; then printf 'msd_file=%s\n' "$(basename "$file")"; else printf 'msd_file=none\n'; fi
hidg=""
for device in /dev/hidg*; do
  [ -c "$device" ] || continue
  if [ -z "$hidg" ]; then hidg="$device"; else hidg="$hidg,$device"; fi
done
printf 'hidg_devices=%s\n' "${{hidg:-none}}"
if [ -c /dev/hidg0 ]; then
  if printf '' > /dev/hidg0 2>/dev/null; then printf 'hid_write=ok\n'; else printf 'hid_write=failed\n'; fi
else
  printf 'hid_write=skipped\n'
fi
"""


def validate_acceptance(facts: dict[str, str], expected_image: str) -> None:
    if facts["gadget_present"] != "yes" or facts["gadget_name"] != "hardened":
        raise ValueError("media/HID acceptance failed: the hardened gadget is absent")
    if facts["udc_bound"] != "yes":
        raise ValueError("media/HID acceptance failed: the gadget is not bound")
    functions = {item for item in facts["functions"].split(",") if item}
    if functions != EXPECTED_GADGET_FUNCTIONS:
        raise ValueError(
            "media/HID acceptance failed: unexpected gadget functions "
            f"{sorted(functions)}"
        )
    if facts["msd_file"] != expected_image:
        raise ValueError(
            f"media/HID acceptance failed: attached image is {facts['msd_file']}"
        )
    if facts["hidg_devices"] == "none":
        raise ValueError("media/HID acceptance failed: no hidg character device")
    for device in facts["hidg_devices"].split(","):
        if not HIDG_DEVICE.fullmatch(device):
            raise ValueError(f"media/HID acceptance failed: invalid hidg device {device}")
    if facts["hid_write"] not in ("ok", "skipped"):
        raise ValueError("media/HID acceptance failed: the report write failed")


def build_teardown_script() -> str:
    return f"""set -eu
root={RUNTIME_ROOT}
marker={MARKER}
if [ -f "$root/owner.pid" ]; then
  pid=$(cat "$root/owner.pid")
  kill "$pid" >/dev/null 2>&1 || true
  i=0
  while [ "$i" -lt 20 ] && kill -0 "$pid" 2>/dev/null; do i=$((i + 1)); sleep 0.5; done
  kill -9 "$pid" >/dev/null 2>&1 || true
  printf 'owner_stopped=yes\\n'
else
  printf 'owner_stopped=yes\\n'
fi
gdir=/sys/kernel/config/usb_gadget
if [ -d "$gdir/hardened" ] && [ -f "$marker" ]; then
  printf '' > "$gdir/hardened/UDC" || true
  for link in "$gdir"/hardened/configs/*/*; do
    [ -L "$link" ] || continue
    rm -f -- "$link"
  done
  for fn in "$gdir"/hardened/functions/*; do
    [ -d "$fn" ] || continue
    rmdir "$fn" 2>/dev/null || true
  done
  for directory in "$gdir"/hardened/configs/*/strings/* "$gdir"/hardened/configs/* "$gdir"/hardened/strings/* "$gdir"/hardened; do
    [ -d "$directory" ] || continue
    rmdir "$directory" 2>/dev/null || true
  done
fi
if [ ! -d "$gdir/hardened" ]; then printf 'hardened_gadget_removed=yes\\n'; else printf 'hardened_gadget_removed=no\\n'; fi
rm -rf -- "$root"
rm -f -- /run/hardened-blikvm-gadget/control.sock
if [ ! -e "$root" ]; then printf 'runtime_removed=yes\\n'; else printf 'runtime_removed=no\\n'; fi
systemctl start kvmd-main.service kvmd-otg.service kvmd.service >/dev/null 2>&1 || true
if systemctl is-active kvmd.service >/dev/null 2>&1; then printf 'kvmd_restarted=yes\\n'; else printf 'kvmd_restarted=no\\n'; fi
i=0
while [ "$i" -lt 20 ]; do
  if [ -n "$(cat "$gdir/kvmd/UDC" 2>/dev/null | tr -d '\\n')" ]; then break; fi
  i=$((i + 1)); sleep 0.5
done
if [ -n "$(cat "$gdir/kvmd/UDC" 2>/dev/null | tr -d '\\n')" ]; then printf 'kvmd_udc_bound=yes\\n'; else printf 'kvmd_udc_bound=no\\n'; fi
"""


def validate_apply(facts: dict[str, str], takeover_udc: bool = False) -> None:
    # The owner serves the control socket on start; the composite gadget is
    # created on demand by the first attach, so gadget facts are informational
    # here and are asserted by the media/HID gates.
    for key in ("socket_present", "owner_started"):
        if facts[key] != "yes":
            raise ValueError(f"apply gate failed: {key}={facts[key]}")
    if takeover_udc and facts["kvmd_udc_unbound"] != "yes":
        raise ValueError(
            f"apply gate failed: the kvmd UDC is still bound ({facts['kvmd_udc_unbound']})"
        )


def validate_teardown(facts: dict[str, str]) -> None:
    for key in (
        "owner_stopped",
        "hardened_gadget_removed",
        "runtime_removed",
        "kvmd_restarted",
        "kvmd_udc_bound",
    ):
        if facts[key] != "yes":
            raise ValueError(f"teardown gate failed: {key}={facts[key]}")


def parse_args_into_plan(options: argparse.Namespace, bundle_path: Path) -> dict[str, Any]:
    import argparse as _argparse

    plan_options = _argparse.Namespace(
        bundle=str(bundle_path),
        output="",
        udc=options.udc,
        power_short_ms=options.power_short_ms,
        power_long_ms=options.power_long_ms,
        reset_ms=options.reset_ms,
        configfs_root=planner.CONFIGFS_ROOT,
        images_dir=f"{planner.GADGET_STATE}/images",
        catalog=f"{planner.GADGET_ETC}/catalog.json",
        serial_file=f"{planner.GADGET_ETC}/serial",
        atx_journal=f"{planner.GADGET_STATE}/atx-journal.json",
        hid_ledger=f"{planner.GADGET_STATE}/hid-ledger.json",
        control_socket=f"{planner.GADGET_RUN}/control.sock",
        atx_chip=options.atx_chip,
        hidg_dir=planner.HIDG_DIR,
        reconciliations="",
    )
    from tools import verify_board_profile_bundle as bundle_verifier

    verified = bundle_verifier.verify_bundle(bundle_path, "")
    plan = planner.build_plan(plan_options, str(verified["sha256"]))
    return plan


def execute(args: argparse.Namespace) -> int:
    output = prototype.validate_output_path(args.output)
    bundle = Path(args.bundle).resolve(strict=True)
    plan = parse_args_into_plan(args, bundle)
    receipt: dict[str, Any] = {
        "schemaVersion": 1,
        "gate": "hardened-blikvm-board-profile-handoff",
        "bundleSha256": plan["bundle"]["sha256"],
        "plan": plan,
        "confirmed": bool(args.confirm_handoff),
        "ownerEnvironment": plan["ownerEnvironment"],
        "acceptance": {
            "mediaHid": bool(args.accept_media_hid),
            "timeoutSeconds": args.accept_timeout_seconds,
            "expectedImage": args.accept_image,
            "operatorDrivesGui": True,
            "takeoverUdc": bool(args.takeover_udc),
            "atxBench": bool(args.accept_atx_bench),
            "physicalDisconnectConfirmed": bool(args.confirm_physical_disconnect),
        },
    }
    if not args.confirm_handoff:
        write_json_0600_atomic(output, receipt)
        print(f"board_gate_plan_only={output} (pass --confirm-handoff to execute)")
        return 0

    host, ssh_port = prototype.parse_endpoint(args.endpoint)
    username = prototype.validate_username(args.username)
    known_hosts = prototype.validate_private_file(args.known_hosts)
    target = prototype.RemoteTarget(host, ssh_port, username, known_hosts)
    secret = prototype.read_secret_stdin()

    if args.teardown:
        result = prototype.run_ssh(target, secret, build_teardown_script(), timeout=60)
        result.check_returncode()
        facts = prototype.parse_facts(result.stdout, set(TEARDOWN_FACTS))
        validate_teardown(facts)
        receipt["teardownFacts"] = facts
    else:
        try:
            apply = prototype.run_ssh(
                target,
                secret,
                build_apply_script(
                    plan,
                    str(plan["bundle"]["sha256"]),
                    takeover_udc=bool(args.takeover_udc),
                ),
                timeout=120,
            )
            if apply.returncode != 0:
                raise ValueError(
                    "apply script failed: "
                    f"stdout={apply.stdout[:400].decode(errors='replace')!r} "
                    f"stderr={apply.stderr[:400].decode(errors='replace')!r}"
                )
            facts = prototype.parse_facts(apply.stdout, set(APPLY_FACTS))
            validate_apply(facts, takeover_udc=bool(args.takeover_udc))
            if args.accept_media_hid:
                acceptance = prototype.run_ssh(
                    target,
                    secret,
                    build_acceptance_script(
                        args.accept_timeout_seconds, args.accept_image
                    ),
                    timeout=args.accept_timeout_seconds + 60,
                )
                acceptance.check_returncode()
                acceptance_facts = prototype.parse_facts(
                    acceptance.stdout, set(ACCEPTANCE_FACTS)
                )
                validate_acceptance(acceptance_facts, args.accept_image)
                receipt["acceptanceFacts"] = acceptance_facts
            if args.accept_atx_bench:
                if not args.confirm_physical_disconnect:
                    raise ValueError(
                        "the ATX bench needs --confirm-physical-disconnect "
                        "(Power and Reset unplugged)"
                    )
                bench = prototype.run_ssh(
                    target,
                    secret,
                    build_atx_bench_script(
                        args.atx_chip,
                        (
                            args.power_short_ms,
                            args.power_long_ms,
                            args.reset_ms,
                        ),
                    ),
                    timeout=120,
                )
                bench.check_returncode()
                bench_facts = prototype.parse_facts(bench.stdout, set(ATX_BENCH_FACTS))
                validate_atx_bench(bench_facts)
                receipt["atxBenchFacts"] = bench_facts
        except Exception:
            try:
                prototype.run_ssh(target, secret, build_teardown_script(), timeout=60)
            except Exception:
                pass
            raise
        receipt["applyFacts"] = facts

    receipt["mutationsPerformed"] = True
    serialized = json.dumps(receipt, sort_keys=True)
    digest = hashlib.sha256(serialized.encode()).hexdigest()
    write_json_0600_atomic(output, receipt)
    print(f"board_gate={output} receiptSha256={digest}")
    return 0


def main() -> int:
    try:
        return execute(parse_args())
    except (OSError, UnicodeError, ValueError, subprocess.SubprocessError) as error:
        print(f"board_gate: {type(error).__name__}: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
