#!/usr/bin/env python3
"""Retire the PiKVM/KVMD stack on the test H616, reversibly.

KVMD stays the fallback until every subsystem is ours. This tool therefore has
two halves:

- ``--inventory`` is read-only and records exactly what a removal would touch
  (the KVMD units, the vendor ATX helper, the config tree, our owner socket and
  the hardened gadget state);
- the removal path requires ``--confirm-removal`` *and* the private receipts
  that prove the replacement works (composite-gadget acceptance, media
  attach/eject, native ATX bench). Without them it refuses, prints the missing
  evidence and changes nothing.

The mutating path only stops/disables the KVMD units after copying their unit
files into a timestamped backup directory, then verifies our owner and gadget
are still alive. ``--restore`` re-enables exactly the units that were enabled.

The remote shell is generated by pure functions and host-tested.
"""

from __future__ import annotations

import argparse
import glob
import json
import re
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

if not __package__:
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from tools.capture_pikvm_baseline import write_json_0600_atomic
from tools import stage_device_prototype as prototype

KVMD_UNITS = (
    "kvmd.service",
    "kvmd-main.service",
    "kvmd-otg.service",
    "kvmd-webterm.service",
)
BACKUP_ROOT = "/var/lib/hardened-blikvm-gadget"
CONTROL_SOCKET = "/run/hardened-blikvm-gadget/control.sock"
MAX_RECEIPT_BYTES = 1_048_576

INVENTORY_FACTS = {
    "kvmd_active",
    "kvmd_main_active",
    "kvmd_otg_active",
    "kvmd_webterm_active",
    "kvmd_unit",
    "kvmd_main_unit",
    "kvmd_otg_unit",
    "kvmd_webterm_unit",
    "vendor_atx_present",
    "kvmd_config_present",
    "owner_socket_present",
    "gadget_present",
    "udc_bound",
    "configfs_mounted",
}
REMOVAL_FACTS = {
    "backup_directory",
    "units_backed_up",
    "kvmd_stopped",
    "owner_socket_present",
    "gadget_present",
    "udc_bound",
}
RESTORE_FACTS = {"kvmd_restored", "kvmd_active"}
TOGGLE_VALUE = re.compile(r"^(yes|no|unknown)$")
PATH_VALUE = re.compile(r"^(|[A-Za-z0-9._/:-]{1,128})$")
TOGGLE_KEYS = {
    "kvmd_active",
    "kvmd_main_active",
    "kvmd_otg_active",
    "kvmd_webterm_active",
    "vendor_atx_present",
    "kvmd_config_present",
    "owner_socket_present",
    "gadget_present",
    "udc_bound",
    "configfs_mounted",
    "kvmd_stopped",
    "units_backed_up",
    "kvmd_restored",
}
PATH_KEYS = {
    "kvmd_unit",
    "kvmd_main_unit",
    "kvmd_otg_unit",
    "kvmd_webterm_unit",
    "backup_directory",
}


def valid_fact_value(key: str, value: str) -> bool:
    if key in TOGGLE_KEYS:
        return bool(TOGGLE_VALUE.fullmatch(value))
    if key in PATH_KEYS:
        return value.startswith("/") and bool(PATH_VALUE.fullmatch(value))
    return bool(PATH_VALUE.fullmatch(value))

REMOTE_INVENTORY = rf"""set -eu
unit_path() {{ systemctl show -p FragmentPath --value "$1" 2>/dev/null || true; }}
active() {{
  state=$(systemctl is-active "$1" 2>/dev/null || true)
  case "$state" in
    active) echo yes ;;
    "") echo unknown ;;
    *) echo no ;;
  esac
}}
printf 'kvmd_active=%s\n' "$(active kvmd.service || true)"
printf 'kvmd_main_active=%s\n' "$(active kvmd-main.service || true)"
printf 'kvmd_otg_active=%s\n' "$(active kvmd-otg.service || true)"
printf 'kvmd_webterm_active=%s\n' "$(active kvmd-webterm.service || true)"
printf 'kvmd_unit=%s\n' "$(unit_path kvmd.service)"
printf 'kvmd_main_unit=%s\n' "$(unit_path kvmd-main.service)"
printf 'kvmd_otg_unit=%s\n' "$(unit_path kvmd-otg.service)"
printf 'kvmd_webterm_unit=%s\n' "$(unit_path kvmd-webterm.service)"
if [ -x /usr/bin/atx ]; then printf 'vendor_atx_present=yes\n'; else printf 'vendor_atx_present=no\n'; fi
if [ -d /etc/kvmd ]; then printf 'kvmd_config_present=yes\n'; else printf 'kvmd_config_present=no\n'; fi
if [ -S {CONTROL_SOCKET} ]; then printf 'owner_socket_present=yes\n'; else printf 'owner_socket_present=no\n'; fi
gdir=/sys/kernel/config/usb_gadget
if [ -d "$gdir/hardened" ]; then printf 'gadget_present=yes\n'; else printf 'gadget_present=no\n'; fi
if [ -n "$(cat "$gdir/hardened/UDC" 2>/dev/null | tr -d '\n')" ]; then printf 'udc_bound=yes\n'; else printf 'udc_bound=no\n'; fi
if mountpoint -q /sys/kernel/config; then printf 'configfs_mounted=yes\n'; else printf 'configfs_mounted=no\n'; fi
"""


def build_removal_script(backup_directory: str) -> str:
    if not re.fullmatch(r"/var/lib/hardened-blikvm-gadget/kvmd-backup-[0-9]{10}", backup_directory):
        raise ValueError("backup directory must be a timestamped path under the runtime root")
    units = " ".join(KVMD_UNITS)
    return f"""set -eu
backup={backup_directory}
mkdir -p "$backup"
copied=yes
for unit in {units}; do
  path=$(systemctl show -p FragmentPath --value "$unit" 2>/dev/null || true)
  if [ -n "$path" ] && [ -f "$path" ]; then
    if ! cp -a "$path" "$backup/"; then copied=no; fi
  fi
done
if [ "$copied" = yes ]; then printf 'units_backed_up=yes\\n'; else printf 'units_backed_up=no\\n'; fi
printf 'backup_directory=%s\\n' "$backup"
for unit in {units}; do
  systemctl disable --now "$unit" >/dev/null 2>&1 || true
done
stopped=yes
for unit in {units}; do
  if systemctl is-active "$unit" >/dev/null 2>&1; then stopped=no; fi
done
if [ "$stopped" = yes ]; then printf 'kvmd_stopped=yes\\n'; else printf 'kvmd_stopped=no\\n'; fi
if [ -S {CONTROL_SOCKET} ]; then printf 'owner_socket_present=yes\\n'; else printf 'owner_socket_present=no\\n'; fi
gdir=/sys/kernel/config/usb_gadget
if [ -d "$gdir/hardened" ]; then printf 'gadget_present=yes\\n'; else printf 'gadget_present=no\\n'; fi
if [ -n "$(cat "$gdir/hardened/UDC" 2>/dev/null | tr -d '\\n')" ]; then printf 'udc_bound=yes\\n'; else printf 'udc_bound=no\\n'; fi
"""


def build_restore_script() -> str:
    units = " ".join(KVMD_UNITS)
    return f"""set -eu
for unit in {units}; do
  systemctl enable --now "$unit" >/dev/null 2>&1 || true
done
if systemctl is-active kvmd.service >/dev/null 2>&1; then printf 'kvmd_active=yes\\n'; else printf 'kvmd_active=no\\n'; fi
if systemctl is-enabled kvmd.service >/dev/null 2>&1; then printf 'kvmd_restored=yes\\n'; else printf 'kvmd_restored=no\\n'; fi
"""


def parse_facts(raw: bytes, allowed: set[str]) -> dict[str, str]:
    facts: dict[str, str] = {}
    for line in raw.decode("utf-8", errors="strict").splitlines():
        if not line:
            continue
        key, separator, value = line.partition("=")
        if not separator or key not in allowed:
            raise ValueError(f"unexpected fact {key!r}")
        if key in facts:
            raise ValueError(f"duplicate fact {key!r}")
        if not valid_fact_value(key, value):
            raise ValueError(f"invalid value for {key!r}")
        facts[key] = value
    missing = allowed - set(facts)
    if missing:
        raise ValueError(f"missing facts: {sorted(missing)}")
    return facts


def evidence_gate(evidence: Path) -> list[str]:
    """Return the missing acceptance evidence, newest receipt first."""
    missing: list[str] = []

    def latest(pattern: str) -> dict[str, Any] | None:
        for candidate in sorted(glob.glob(str(evidence / pattern)), reverse=True):
            path = Path(candidate)
            try:
                if path.stat().st_size > MAX_RECEIPT_BYTES:
                    continue
                document = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, UnicodeError, json.JSONDecodeError):
                continue
            if isinstance(document, dict):
                return document
        return None

    acceptance = latest("board-handoff-acceptance-*.json")
    if not acceptance:
        missing.append("board-handoff-acceptance-*.json (composite gadget acceptance)")
    else:
        facts = acceptance.get("acceptanceFacts") or {}
        if facts.get("gadget_present") != "yes" or facts.get("udc_bound") != "yes":
            missing.append("a passing composite-gadget acceptance receipt")

    media = latest("restricted-control-media-gate-*.json")
    if not media or media.get("probe") != "restricted-control-media-attach-eject":
        missing.append("restricted-control-media-gate-*.json (media attach/eject)")

    atx = latest("atx-gpio-bench-*.json")
    if not atx or atx.get("result") != "passed":
        missing.append("atx-gpio-bench-*.json (native ATX pulse bench)")

    return missing


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--endpoint", required=True)
    _ = parser.add_argument("--username", required=True)
    _ = parser.add_argument("--known-hosts", required=True)
    _ = parser.add_argument("--output", required=True)
    _ = parser.add_argument("--evidence", default="evidence/private")
    _ = parser.add_argument("--inventory", action="store_true")
    _ = parser.add_argument("--confirm-removal", action="store_true")
    _ = parser.add_argument("--restore", action="store_true")
    _ = parser.add_argument("--backup-directory", default="")
    return parser.parse_args()


def execute(args: argparse.Namespace) -> int:
    output = prototype.validate_output_path(args.output)
    evidence = Path(args.evidence)
    receipt: dict[str, Any] = {
        "schemaVersion": 1,
        "probe": "hardened-blikvm-kvmd-removal",
        "mode": "inventory"
        if args.inventory
        else ("restore" if args.restore else "removal"),
        "policy": {
            "credentialsRead": False,
            "kvmdUnitsStopped": not args.inventory and not args.restore,
            "unitsBackedUp": not args.inventory and not args.restore,
        },
    }

    if not args.inventory and not args.restore:
        missing = evidence_gate(evidence)
        if missing:
            receipt["refused"] = True
            receipt["missingEvidence"] = missing
            write_json_0600_atomic(output, receipt)
            print(
                "refused: KVMD stays the fallback until the replacement is proven; "
                f"missing {', '.join(missing)}"
            )
            return 3

    host, ssh_port = prototype.parse_endpoint(args.endpoint)
    username = prototype.validate_username(args.username)
    known_hosts = prototype.validate_private_file(args.known_hosts)
    target = prototype.RemoteTarget(host, ssh_port, username, known_hosts)
    secret = prototype.read_secret_stdin()

    if args.inventory:
        result = prototype.run_ssh(target, secret, REMOTE_INVENTORY, timeout=60)
        result.check_returncode()
        facts = parse_facts(result.stdout, set(INVENTORY_FACTS))
        receipt["inventory"] = facts
    elif args.restore:
        result = prototype.run_ssh(target, secret, build_restore_script(), timeout=60)
        result.check_returncode()
        facts = parse_facts(result.stdout, set(RESTORE_FACTS))
        if facts["kvmd_restored"] != "yes" or facts["kvmd_active"] != "yes":
            raise ValueError("KVMD restore did not complete")
        receipt["restore"] = facts
    else:
        if not args.confirm_removal:
            write_json_0600_atomic(output, receipt)
            print("plan only: pass --confirm-removal to stop the KVMD units")
            return 0
        backup = args.backup_directory or f"{BACKUP_ROOT}/kvmd-backup-{int(time.time())}"
        script = build_removal_script(backup)
        result = prototype.run_ssh(target, secret, script, timeout=120)
        result.check_returncode()
        facts = parse_facts(result.stdout, set(REMOVAL_FACTS))
        if (
            facts["kvmd_stopped"] != "yes"
            or facts["owner_socket_present"] != "yes"
            or facts["gadget_present"] != "yes"
        ):
            raise ValueError("KVMD removal did not leave our owner serving")
        receipt["removal"] = facts

    write_json_0600_atomic(output, receipt)
    print(f"kvmd_removal={output} mode={receipt['mode']}")
    return 0


def main() -> int:
    try:
        return execute(parse_args())
    except (OSError, UnicodeError, ValueError, subprocess.SubprocessError) as error:
        print(f"kvmd_removal: {type(error).__name__}: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
